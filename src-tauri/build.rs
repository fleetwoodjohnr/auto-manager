//! The IPC allow-list and handler list, generated from the `#[tauri::command]` functions in
//! src/commands/, so the two can never drift apart. Tauri generates an `allow-<command>`
//! permission for each command; this script writes the capability granting exactly those plus
//! CORE_PERMISSIONS. Anything else is rejected at the IPC boundary.

use std::fmt::Write as _;

/// Core and plugin permissions the webview needs. No shell, fs or http access: files are only
/// reached through commands, with paths the person picked in a native dialog.
const CORE_PERMISSIONS: &[&str] = &[
    "core:event:default",
    "core:window:allow-set-title",
    "core:webview:allow-print",
    "dialog:allow-open",
    "dialog:allow-save",
    "dialog:allow-ask",
    "dialog:allow-confirm",
    "dialog:allow-message",
    "opener:allow-reveal-item-in-dir",
    "process:allow-restart",
];

fn commands() -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut files: Vec<_> = std::fs::read_dir("src/commands").expect("src/commands").filter_map(Result::ok).map(|e| e.path()).collect();
    files.sort();
    for path in files {
        println!("cargo:rerun-if-changed={}", path.display());
        let module = path.file_stem().and_then(|s| s.to_str()).unwrap_or_default().to_string();
        let text = std::fs::read_to_string(&path).expect("read command file");
        let mut pending = false;
        for line in text.lines() {
            let t = line.trim();
            if t.starts_with("#[tauri::command") {
                pending = true;
            } else if pending && (t.starts_with("pub fn ") || t.starts_with("pub async fn ")) {
                let name = t.trim_start_matches("pub ").trim_start_matches("async ").trim_start_matches("fn ");
                let name: String = name.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
                out.push((module.clone(), name));
                pending = false;
            }
        }
    }
    out
}

fn main() {
    let cmds = commands();
    // build scripts run once; leaking gives tauri-build the 'static list it wants.
    let names: &'static [&'static str] =
        Box::leak(cmds.iter().map(|(_, n)| &*Box::leak(n.clone().into_boxed_str())).collect::<Vec<_>>().into_boxed_slice());

    let mut handlers = String::from("tauri::generate_handler![\n");
    for (m, n) in &cmds {
        writeln!(handlers, "    crate::commands::{m}::{n},").expect("write");
    }
    handlers.push(']');
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("handlers.rs");
    std::fs::write(out, handlers).expect("write handlers");

    // Links open in the browser only for web addresses (official manual portals, NHTSA, GitHub).
    let opener = serde_json::json!({ "identifier": "opener:allow-open-url", "allow": [{ "url": "https://*" }, { "url": "http://*" }] });
    let permissions: Vec<serde_json::Value> = CORE_PERMISSIONS
        .iter()
        .map(|p| serde_json::json!(p))
        .chain(std::iter::once(opener))
        .chain(names.iter().map(|c| serde_json::json!(format!("allow-{}", c.replace('_', "-")))))
        .collect();
    let capability = serde_json::json!({
        "$schema": "../gen/schemas/desktop-schema.json",
        "identifier": "main",
        "description": "Generated by build.rs from the #[tauri::command] functions. Do not edit.",
        "windows": ["main"],
        "permissions": permissions,
    });
    let text = serde_json::to_string_pretty(&capability).expect("serialize capability") + "\n";
    let path = "capabilities/main.json";
    if std::fs::read_to_string(path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(path, text).expect("write capability");
    }

    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(names)))
        .expect("failed to run tauri-build");
}
